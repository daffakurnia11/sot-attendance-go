DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'safebox_stock_transactions'
          AND column_name = 'id'
          AND is_identity = 'NO'
    ) THEN
        ALTER TABLE safebox_stock_transactions
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

SELECT setval(
    pg_get_serial_sequence('public.safebox_stock_transactions', 'id'),
    GREATEST(COALESCE((SELECT MAX(id) FROM safebox_stock_transactions), 0) + 1, 1),
    false
);
