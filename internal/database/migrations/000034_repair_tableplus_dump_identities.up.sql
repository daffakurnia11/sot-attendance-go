DO $$
DECLARE
    relation_name TEXT;
    sequence_name TEXT;
BEGIN
    FOREACH relation_name IN ARRAY ARRAY[
        'crafting_recipes',
        'crafting_recipe_items',
        'safebox_stock_items',
        'safebox_stock_balances',
        'safebox_stock_transactions'
    ]
    LOOP
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = relation_name
              AND column_name = 'id'
              AND is_identity = 'NO'
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                relation_name
            );
        END IF;

        sequence_name := pg_get_serial_sequence('public.' || relation_name, 'id');
        EXECUTE format(
            'SELECT setval(%L, GREATEST(COALESCE((SELECT MAX(id) FROM public.%I), 0) + 1, 1), false)',
            sequence_name,
            relation_name
        );
    END LOOP;
END
$$;
